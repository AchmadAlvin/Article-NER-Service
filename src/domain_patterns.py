def normalize_entity(text: str, label: str) -> Optional[str]:
    clean = text.strip().lower()


    if clean.startswith("the "):
        clean_no_art = clean[4:].strip()
        if clean_no_art in ENTITY_NORMALIZATIONS:
            return ENTITY_NORMALIZATIONS[clean_no_art]


